"""Run every Part 3 task in order and write the graded transcripts.

Nothing in README.md's Part 3 number block is typed by hand. This script
writes transcripts/part3-readme-numbers.md and README.md carries that block,
same rule as scripts/run_part1.py and scripts/run_part2.py, and the same
reason.
"""

import json
